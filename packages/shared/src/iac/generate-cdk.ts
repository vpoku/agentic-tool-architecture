export function generateFullIac(proposal: ArchitectureProposal) {
  return {
    cdk: generateCdkStack(proposal),
    deployScript: generateDeployScript(proposal.projectId),
    readme: generateReadme(proposal),
    copilotPrompt: generateCopilotPrompt(proposal),
  };
}

function toPascalCase(str: string): string {
  return replaceNonAlpha(str)
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join("") || "Workload";
}

function replaceNonAlpha(str: string): string {
  return str.replace(/[^a-zA-Z0-9-_ ]/g, "");
}

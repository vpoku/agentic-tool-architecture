import type { ArchitectureProposal } from "../schemas/architecture.js";

export function generateCdkStack(proposal: ArchitectureProposal): string {
  const serviceNames = proposal.services.map((s) => s.data.service);
  const hasVpc = serviceNames.some((s) => s.toLowerCase().includes("vpc"));
  const hasS3 = serviceNames.some((s) => s.toLowerCase().includes("s3"));
  const hasLambda = serviceNames.some((s) => s.toLowerCase().includes("lambda"));
  const hasDynamoDb = serviceNames.some((s) => s.toLowerCase().includes("dynamodb"));
  const hasApiGateway = serviceNames.some((s) => s.toLowerCase().includes("api gateway"));
  const hasSqs = serviceNames.some((s) => s.toLowerCase().includes("sqs"));
  const hasKms = serviceNames.some((s) => s.toLowerCase().includes("kms"));
  const hasCloudWatch = serviceNames.some((s) => s.toLowerCase().includes("cloudwatch"));

  return `import * as cdk from "aws-cdk-lib";
import * as s3 from "aws-cdk-lib/aws-s3";
import * as lambda from "aws-cdk-lib/aws-lambda";
import * as dynamodb from "aws-cdk-lib/aws-dynamodb";
import * as apigatewayv2 from "aws-cdk-lib/aws-apigatewayv2";
import * as sqs from "aws-cdk-lib/aws-sqs";
import * as kms from "aws-cdk-lib/aws-kms";
import * as logs from "aws-cdk-lib/aws-logs";
import * as ec2 from "aws-cdk-lib/aws-ec2";
import * as iam from "aws-cdk-lib/aws-iam";
import { HttpLambdaIntegration } from "aws-cdk-lib/aws-apigatewayv2-integrations";
import { SqsEventSource } from "aws-cdk-lib/aws-lambda-event-sources";
import { Construct } from "constructs";

export interface ${toPascalCase(proposal.projectId)}StackProps extends cdk.StackProps {
  environmentName?: string;
}

/**
 * Generated by CloudArch Architect
 * Project: ${proposal.projectId}
 * Summary: ${proposal.summary.replace(/"/g, '\\"')}
 * Compliance: ${proposal.compliance.framework} ${proposal.compliance.level}
 */
export class ${toPascalCase(proposal.projectId)}Stack extends cdk.Stack {
  constructor(scope: Construct, id: string, props?: ${toPascalCase(proposal.projectId)}StackProps) {
    super(scope, id, props);

    const envName = props?.environmentName ?? "prod";

    ${hasKms ? `const encryptionKey = new kms.Key(this, "EncryptionKey", {
      enableKeyRotation: true,
      alias: \`\${envName}-cloudarch-key\`,
      description: "Customer-managed key for ${proposal.compliance.framework} workload",
    });` : ""}

    ${hasVpc ? `const vpc = new ec2.Vpc(this, "Vpc", {
      maxAzs: 2,
      natGateways: 1,
      subnetConfiguration: [
        { name: "Public", subnetType: ec2.SubnetType.PUBLIC },
        { name: "Private", subnetType: ec2.SubnetType.PRIVATE_WITH_EGRESS },
      ],
    });` : ""}

    ${hasS3 ? `const documentsBucket = new s3.Bucket(this, "DocumentsBucket", {
      encryption: s3.BucketEncryption.KMS,
      ${hasKms ? "encryptionKey," : ""}
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      enforceSSL: true,
      versioned: true,
      removalPolicy: cdk.RemovalPolicy.RETAIN,
    });` : ""}

    ${hasDynamoDb ? `const metadataTable = new dynamodb.Table(this, "MetadataTable", {
      partitionKey: { name: "documentId", type: dynamodb.AttributeType.STRING },
      billingMode: dynamodb.BillingMode.PAY_PER_REQUEST,
      ${hasKms ? "encryption: dynamodb.TableEncryption.CUSTOMER_MANAGED, encryptionKey," : "encryption: dynamodb.TableEncryption.AWS_MANAGED,"}
      pointInTimeRecovery: true,
      removalPolicy: cdk.RemovalPolicy.RETAIN,
    });` : ""}

    ${hasSqs ? `const processingQueue = new sqs.Queue(this, "ProcessingQueue", {
      encryption: sqs.QueueEncryption.KMS,
      ${hasKms ? "encryptionMasterKey: encryptionKey," : ""}
      visibilityTimeout: cdk.Duration.seconds(300),
    });` : ""}

    ${hasLambda ? `const processorFn = new lambda.Function(this, "DocumentProcessor", {
      runtime: lambda.Runtime.NODEJS_20_X,
      handler: "index.handler",
      code: lambda.Code.fromInline("exports.handler = async () => ({ statusCode: 200 });"),
      timeout: cdk.Duration.seconds(30),
      ${hasVpc ? "vpc," : ""}
      environment: {
        ${hasS3 ? "BUCKET_NAME: documentsBucket.bucketName," : ""}
        ${hasDynamoDb ? "TABLE_NAME: metadataTable.tableName," : ""}
        ${hasSqs ? "QUEUE_URL: processingQueue.queueUrl," : ""}
      },
    });

    ${hasS3 ? "documentsBucket.grantReadWrite(processorFn);" : ""}
    ${hasDynamoDb ? "metadataTable.grantReadWriteData(processorFn);" : ""}
    ${hasSqs ? `processingQueue.grantConsumeMessages(processorFn);
    processorFn.addEventSource(new SqsEventSource(processingQueue, { batchSize: 10 }));` : ""}` : ""}

    ${hasApiGateway && hasLambda ? `const httpApi = new apigatewayv2.HttpApi(this, "IntakeApi", {
      apiName: \`\${envName}-intake-api\`,
    });

    httpApi.addRoutes({
      path: "/documents",
      methods: [apigatewayv2.HttpMethod.POST],
      integration: new HttpLambdaIntegration("IntakeIntegration", processorFn),
    });` : ""}

    ${hasCloudWatch ? `new logs.LogGroup(this, "ApplicationLogs", {
      retention: logs.RetentionDays.ONE_YEAR,
      ${hasKms ? "encryptionKey," : ""}
      removalPolicy: cdk.RemovalPolicy.RETAIN,
    });` : ""}

    new cdk.CfnOutput(this, "ComplianceFramework", {
      value: "${proposal.compliance.framework}",
      description: "Target compliance framework",
    });
  }
}
`;
}

export function generateDeployScript(projectId: string): string {
  return `#!/usr/bin/env bash
set -euo pipefail

# CloudArch Architect — Deploy Script
# Project: ${projectId}
# Region: us-gov-west-1 (AWS GovCloud)

PROFILE="\${AWS_PROFILE:-govcloud}"
REGION="\${AWS_REGION:-us-gov-west-1}"
ACCOUNT=$(aws sts get-caller-identity --profile "$PROFILE" --query Account --output text)

echo "Deploying to GovCloud account $ACCOUNT in $REGION..."

cd "$(dirname "$0")/../infra"

npm install
npm run build

# Bootstrap CDK (first time only)
npx cdk bootstrap "aws://$ACCOUNT/$REGION" --profile "$PROFILE"

# Deploy stack
npx cdk deploy --all --profile "$PROFILE" --require-approval never

echo "Deployment complete."
`;
}

